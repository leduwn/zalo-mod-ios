#!/usr/bin/env python3
"""Validate the shared compatibility manifest and emit Objective-C data."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path


def load_targets(path: Path) -> list[dict[str, object]]:
    payload = json.loads(path.read_text(encoding="utf-8"))
    targets = payload.get("targets")
    if not isinstance(targets, list) or not targets:
        raise ValueError("targets must be a non-empty array")
    seen: set[tuple[str, str]] = set()
    validated = []
    for index, target in enumerate(targets):
        if not isinstance(target, dict):
            raise ValueError(f"target {index} must be an object")
        version = target.get("version")
        build = target.get("build")
        bundles = target.get("bundleIdentifiers")
        if not isinstance(version, str) or not version:
            raise ValueError(f"target {index} requires version")
        if not isinstance(build, str) or not build:
            raise ValueError(f"target {index} requires build")
        if not isinstance(bundles, list) or not bundles or not all(isinstance(v, str) and v for v in bundles):
            raise ValueError(f"target {index} requires bundleIdentifiers")
        identity = (version, build)
        if identity in seen:
            raise ValueError(f"duplicate target {version}/{build}")
        seen.add(identity)
        validated.append({"version": version, "build": build, "bundleIdentifiers": bundles})
    return validated


def objc_string(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'@"{escaped}"'


def render_header(targets: list[dict[str, object]]) -> str:
    rows = []
    for target in targets:
        bundles = ", ".join(objc_string(value) for value in target["bundleIdentifiers"])
        rows.append(
            "        @{ @\"version\": %s, @\"build\": %s, @\"bundleIdentifiers\": @[ %s ] }"
            % (objc_string(target["version"]), objc_string(target["build"]), bundles)
        )
    body = ",\n".join(rows)
    return (
        "// Generated by Scripts/generate_compatibility.py. Do not edit.\n"
        "static NSArray<NSDictionary *> *ZLModSupportedHostRecords(void) {\n"
        "    static NSArray<NSDictionary *> *records;\n"
        "    static dispatch_once_t onceToken;\n"
        "    dispatch_once(&onceToken, ^{\n"
        "        records = @[\n"
        f"{body}\n"
        "        ];\n"
        "    });\n"
        "    return records;\n"
        "}\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("manifest", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    try:
        targets = load_targets(args.manifest)
        rendered = render_header(targets)
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(rendered, encoding="utf-8", newline="\n")
    except (OSError, ValueError, json.JSONDecodeError) as error:
        print(error, file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
